def ja(text: str) -> str:
    """Translate known interface copy, leaving model/provider content unchanged."""
    value = str(text)
    if value in _JA:
        return _JA[value]
    prefixes = (
        ("Loading ", "読み込み中: "),
        ("Unloading ", "解放中: "),
        ("Delete “", "「"),
        ("Could not ", "できませんでした: "),
        ("Failed to ", "失敗しました: "),
    )
    for source, target in prefixes:
        if value.startswith(source):
            return target + value[len(source):]
    return value


def localize_widget_tree(root) -> None:
    """Translate static interface widgets after page creation without touching user data."""
    from PySide6.QtWidgets import (
        QAbstractButton,
        QComboBox,
        QDialog,
        QGroupBox,
        QLabel,
        QLineEdit,
        QPlainTextEdit,
        QTableWidget,
        QTextEdit,
        QWidget,
    )

    for widget in [root, *root.findChildren(QWidget)]:
        if isinstance(widget, QDialog):
            widget.setWindowTitle(ja(widget.windowTitle()))
        if isinstance(widget, QAbstractButton):
            widget.setText(ja(widget.text()))
        elif isinstance(widget, QLabel):
            widget.setText(ja(widget.text()))
        if isinstance(widget, QGroupBox):
            widget.setTitle(ja(widget.title()))
        if isinstance(widget, QLineEdit):
            widget.setPlaceholderText(ja(widget.placeholderText()))
        elif isinstance(widget, (QPlainTextEdit, QTextEdit)):
            widget.setPlaceholderText(ja(widget.placeholderText()))
        if isinstance(widget, QComboBox):
            for index in range(widget.count()):
                widget.setItemText(index, ja(widget.itemText(index)))
        if isinstance(widget, QTableWidget):
            for column in range(widget.columnCount()):
                item = widget.horizontalHeaderItem(column)
                if item is not None:
                    item.setText(ja(item.text()))
        for action in widget.actions():
            action.setText(ja(action.text()))
        tooltip = widget.toolTip()
        if tooltip:
            widget.setToolTip(ja(tooltip))
